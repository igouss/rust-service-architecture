use gates::views::{crates, machines};

use crate::{lifecycles, package, workspace};

const TASK: &str = "pub enum Task { Absent, Open { title: String }, Done }
pub enum TaskEvent { Added { title: String }, Completed }
impl Lifecycle for Task {
    type Event = TaskEvent;
    fn initial() -> Task {
        Task::Absent
    }
    fn evolve(self, event: &TaskEvent) -> Task {
        match (self, event) {
            (Task::Absent, TaskEvent::Added { title }) => Task::Open { title: title.clone() },
            (Task::Open { .. }, TaskEvent::Completed) => Task::Done,
            (s @ Task::Absent, TaskEvent::Completed)
            | (s @ Task::Open { .. }, TaskEvent::Added { .. })
            | (s @ Task::Done, TaskEvent::Added { .. } | TaskEvent::Completed) => s,
        }
    }
}";

fn drawn(text: &str) -> Result<String, String> {
    lifecycles(text).and_then(|read| machines(&read)).map_err(|unread| unread.0)
}

#[test]
fn a_workspace_of_one_crate_is_a_node_with_no_arrow() {
    assert_eq!(
        crates(&workspace(&package("domain", "domain", &[("serde", None)]))),
        "# Crate graph\n\nGenerated by `just views` from `cargo metadata`. An arrow points from a crate to one it depends on;\na dotted arrow is a dev-dependency.\n\n```mermaid\ngraph TD\n    domain[\"domain<br/><i>domain</i>\"]\n```\n"
    );
}

#[test]
fn each_dependency_on_a_member_is_an_arrow_and_a_test_dependency_is_dotted() {
    assert_eq!(
        crates(&workspace(&[package("adapter-store", "driven-adapter", &[("ports", None), ("domain", Some("dev"))]), package("domain", "domain", &[]), package("ports", "port-and-adapter", &[("domain", None)])].join(","))),
        "# Crate graph\n\nGenerated by `just views` from `cargo metadata`. An arrow points from a crate to one it depends on;\na dotted arrow is a dev-dependency.\n\n```mermaid\ngraph TD\n    adapter_store[\"adapter-store<br/><i>driven-adapter</i>\"]\n    domain[\"domain<br/><i>domain</i>\"]\n    ports[\"ports<br/><i>port-and-adapter</i>\"]\n    adapter_store -.-> domain\n    adapter_store --> ports\n    ports --> domain\n```\n"
    );
}

#[test]
fn a_lifecycle_is_drawn_from_its_initial_state_and_the_arms_that_change_it() {
    assert_eq!(
        drawn(TASK),
        Ok(String::from("# State machines\n\nGenerated by `just views` from each lifecycle's `evolve`. An arm that returns the state it was\ngiven is not drawn.\n\n## Task\n\n`fixture.rs`\n\n```mermaid\nstateDiagram-v2\n    [*] --> Absent\n    Absent --> Open: Added\n    Open --> Done: Completed\n```\n"))
    );
}

#[test]
fn an_arm_of_several_states_and_events_draws_each_pair() {
    assert_eq!(
        drawn(
            &TASK
                .replace(
                    "(Task::Open { .. }, TaskEvent::Completed) => Task::Done,",
                    "(Task::Open { .. } | Task::Done, TaskEvent::Completed) => Task::Done,"
                )
                .replace("| TaskEvent::Completed) => s", ") => s")
        )
        .map(|text| text
            .lines()
            .filter(|line| line.contains("-->"))
            .map(str::trim)
            .collect::<Vec<&str>>()
            .join("; ")),
        Ok(String::from(
            "[*] --> Absent; Absent --> Open: Added; Open --> Done: Completed; Done --> Done: Completed"
        ))
    );
}

#[test]
fn an_evolve_that_does_more_than_match_is_unread() {
    assert_eq!(
        drawn(&TASK.replace("match (self, event) {", "let _ = 1;\n        match (self, event) {")),
        Err(String::from("Task: `evolve` is not one `match (self, event)`"))
    );
}

#[test]
fn an_arm_that_is_not_a_pair_of_variants_is_unread() {
    assert_eq!(
        drawn(&TASK.replace(
            "| (s @ Task::Done, TaskEvent::Added { .. } | TaskEvent::Completed) => s",
            "| (s @ Task::Done, _) => s"
        )),
        Err(String::from("Task: the arm `(s @ Task::Done, _)` is not a pair of Task and TaskEvent variants"))
    );
}

#[test]
fn an_arm_that_returns_neither_a_state_nor_the_state_given_is_unread() {
    assert_eq!(
        drawn(&TASK.replace("=> s,", "=> reopened(s),")),
        Err(String::from("Task: `reopened(s)` is neither a state nor the state it was given"))
    );
}

#[test]
fn an_evolve_that_leaves_a_pair_out_is_unread() {
    assert_eq!(
        drawn(&TASK.replace("| TaskEvent::Completed) => s", ") => s")),
        Err(String::from("Task: `evolve` has 6 pairs of state and event, its arms cover 5"))
    );
}

#[test]
fn a_match_inside_an_arm_is_unread() {
    assert_eq!(
        drawn(&TASK.replace(
            "=> Task::Done,",
            "=> Task::Open { title: match 1 { 1 => String::new(), 0 | 2..=255 => String::new() } },"
        )),
        Err(String::from("Task: `evolve` has 6 pairs of state and event, its arms cover 6"))
    );
}

#[test]
fn an_initial_that_does_not_open_with_a_state_is_unread() {
    assert_eq!(
        drawn(&TASK.replace("        Task::Absent\n", "        let first = Task::Absent;\n        first\n")),
        Err(String::from("Task: `initial` does not return a variant of Task"))
    );
}
