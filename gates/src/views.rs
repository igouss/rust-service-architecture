pub fn crates(workspace: &Workspace) -> String {
    let id = |name: &str| name.replace('-', "_");
    let mut lines: Vec<String> = vec![
        String::from("# Crate graph"),
        String::new(),
        String::from("Generated by `just views` from `cargo metadata`. An arrow points from a crate to one it depends on;"),
        String::from("a dotted arrow is a dev-dependency."),
        String::new(),
        String::from("```mermaid"),
        String::from("graph TD"),
    ];
    for package in &workspace.packages {
        lines.push(format!(
            "    {}[\"{}<br/><i>{}</i>\"]",
            id(&package.name),
            package.name,
            package.role().unwrap_or("untagged")
        ));
    }
    for package in &workspace.packages {
        let mut held: Vec<&Dependency> = package
            .dependencies
            .iter()
            .filter(|dependency| workspace.packages.iter().any(|member| member.name == dependency.name))
            .collect();
        held.sort_by(|one, other| one.name.cmp(&other.name));
        for dependency in held {
            let arrow: &str = if dependency.kind.as_deref() == Some("dev") { "-.->" } else { "-->" };
            lines.push(format!("    {} {arrow} {}", id(&package.name), id(&dependency.name)));
        }
    }
    lines.push(String::from("```"));
    lines.push(String::new());
    lines.join("\n")
}

fn function<'a>(item: &'a ItemImpl, name: &str) -> Option<&'a ImplItemFn> {
    item.items.iter().find_map(|inner| {
        if let ImplItem::Fn(function) = inner {
            (function.sig.ident == name).then_some(function)
        } else {
            None
        }
    })
}

fn evolve(function: &ImplItemFn) -> Option<&ExprMatch> {
    let [Stmt::Expr(Expr::Match(matched), None)] = function.block.stmts.as_slice() else {
        return None;
    };
    let Expr::Tuple(pair) = &*matched.expr else {
        return None;
    };
    let named = |index: usize, wanted: Option<&str>| {
        pair.elems.iter().nth(index).is_some_and(|element| {
            if let Expr::Path(path) = element {
                path.path.get_ident().is_some_and(|ident| wanted.is_none_or(|name| ident == name))
            } else {
                false
            }
        })
    };
    (matched.attrs.is_empty() && pair.elems.len() == 2 && named(0, Some("self")) && named(1, None)).then_some(matched)
}

fn halves(alternative: &Pat) -> Vec<&Pat> {
    if let Pat::Tuple(tuple) = alternative {
        return tuple.elems.iter().collect();
    }
    if let Pat::Paren(inner) = alternative {
        return vec![&inner.pat];
    }
    Vec::new()
}

fn given(halves: &[&Pat]) -> Option<String> {
    halves.first().and_then(|first| {
        if let Pat::Ident(syn::PatIdent { subpat: Some(_), ident, .. }) = first {
            Some(ident.to_string())
        } else {
            None
        }
    })
}

/// The transitions `evolve` draws, as (from, to, by), in the order written.
pub fn edges(lifecycles: &Lifecycles, found: &Found) -> Result<Vec<(String, String, String)>, Unread> {
    let (state, event): (&str, &str) = (&found.state, &found.event);
    let unread = || Unread(format!("{state}: `evolve` is not one `match (self, event)`"));
    let source = lifecycles.source(found).ok_or_else(unread)?;
    let function: &ImplItemFn = function(&found.item, "evolve").ok_or_else(unread)?;
    let matched: &ExprMatch = evolve(function).ok_or_else(unread)?;
    let mut drawn: Vec<(String, String, String)> = Vec::new();
    let mut pairs: BTreeSet<(String, String)> = BTreeSet::new();
    for arm in &matched.arms {
        let then: &str = source.slice(arm.body.span()).trim();
        let target: Option<String> = opening(&arm.body.to_token_stream(), state);
        let alternatives: Vec<&Pat> = if let Pat::Or(either) = &arm.pat {
            either.cases.iter().collect()
        } else {
            vec![&arm.pat]
        };
        for alternative in alternatives {
            let halves: Vec<&Pat> = halves(alternative);
            let (sources, triggers): (Vec<String>, Vec<String>) = if let [from, by] = halves.as_slice() {
                (paths(&from.to_token_stream(), state), paths(&by.to_token_stream(), event))
            } else {
                (Vec::new(), Vec::new())
            };
            if sources.is_empty() || triggers.is_empty() {
                return Err(Unread(format!(
                    "{state}: the arm `{}` is not a pair of {state} and {event} variants",
                    squeezed(source.slice(alternative.span()))
                )));
            }
            if target.is_none() && given(&halves).as_deref() != Some(then) {
                return Err(Unread(format!("{state}: `{}` is neither a state nor the state it was given", squeezed(then))));
            }
            for from in &sources {
                for by in &triggers {
                    pairs.insert((from.clone(), by.clone()));
                    drawn.extend(target.iter().map(|to| (from.clone(), to.clone(), by.clone())));
                }
            }
        }
    }
    let member = lifecycles.member(found)?;
    let (states, events): (Vec<String>, Vec<String>) = (member.variants(state)?, member.variants(event)?);
    let every: BTreeSet<(String, String)> = states.iter().flat_map(|from| events.iter().map(move |by| (from.clone(), by.clone()))).collect();
    if pairs != every || matched.arms.len() != fat_arrows(&function.block.to_token_stream()) {
        return Err(Unread(format!(
            "{state}: `evolve` has {} pairs of state and event, its arms cover {}",
            every.len(),
            pairs.len()
        )));
    }
    Ok(drawn)
}

fn initial(found: &Found) -> Option<String> {
    let function: &ImplItemFn = function(&found.item, "initial")?;
    let returns: bool = if let ReturnType::Type(_, returned) = &function.sig.output {
        plain(returned).is_some()
    } else {
        false
    };
    let first: &Stmt = function.block.stmts.first()?;
    (function.sig.inputs.is_empty() && returns)
        .then(|| opening(&first.to_token_stream(), &found.state))
        .flatten()
}

pub fn machines(lifecycles: &Lifecycles) -> Result<String, Unread> {
    let mut lines: Vec<String> = vec![
        String::from("# State machines"),
        String::new(),
        String::from("Generated by `just views` from each lifecycle's `evolve`. An arm that returns the state it was"),
        String::from("given is not drawn."),
        String::new(),
    ];
    for found in &lifecycles.found {
        let state: &str = &found.state;
        let starts: String = initial(found).ok_or_else(|| Unread(format!("{state}: `initial` does not return a variant of {state}")))?;
        let shown: &str = lifecycles.source(found).map_or("", |source| source.shown.as_str());
        lines.extend([
            format!("## {state}"),
            String::new(),
            format!("`{shown}`"),
            String::new(),
            String::from("```mermaid"),
            String::from("stateDiagram-v2"),
            format!("    [*] --> {starts}"),
        ]);
        lines.extend(
            edges(lifecycles, found)?
                .iter()
                .map(|edge| format!("    {} --> {}: {}", edge.0, edge.1, edge.2)),
        );
        lines.extend([String::from("```"), String::new()]);
    }
    Ok(lines.join("\n"))
}

struct Wanted {
    folder: PathBuf,
    views: Vec<(&'static str, String)>,
}

fn wanted() -> Result<Wanted, Unread> {
    let workspace: Workspace = Workspace::read()?;
    let machines: String = machines(&Lifecycles::read(&workspace)?)?;
    Ok(Wanted {
        folder: workspace.root.join("docs").join("views"),
        views: vec![("crates.md", crates(&workspace)), ("state-machines.md", machines)],
    })
}

pub fn views(asked: &[String]) -> Result<Verdict, Unread> {
    let Wanted { folder, views: wanted }: Wanted = wanted().map_err(|unread| {
        Unread(format!(
            "{}; the view would leave it out\nFix: write `evolve` as one `match (self, event)` whose arms pair variants and return a state or `s` from `s @`.",
            unread.0
        ))
    })?;
    if asked.iter().map(String::as_str).eq(["--check"]) {
        let stale = wanted
            .iter()
            .filter(|view| std::fs::read_to_string(folder.join(view.0)).ok().as_ref() != Some(&view.1));
        return Ok(Verdict {
            found: stale.map(|view| format!("docs/views/{} is stale: run `just views`", view.0)).collect(),
            fix: Vec::new(),
        });
    }
    std::fs::create_dir_all(&folder).map_err(|error| Unread(format!("{}: {error}", folder.display())))?;
    for (name, text) in &wanted {
        std::fs::write(folder.join(name), text).map_err(|error| Unread(format!("docs/views/{name}: {error}")))?;
        println!("wrote docs/views/{name}");
    }
    Ok(Verdict {
        found: Vec::new(),
        fix: Vec::new(),
    })
}
