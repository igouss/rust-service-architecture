#!/usr/bin/env python3
import glob, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "docs", "views")


def crates():
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--no-deps"], cwd=ROOT, capture_output=True, text=True, check=True).stdout)
    members = {p["name"]: p for p in meta["packages"]}
    lines = ["# Crate graph", "", "Generated by `just views` from `cargo metadata`. An arrow points from a crate to one it depends on;", "a dotted arrow is a dev-dependency.", "", "```mermaid", "graph TD"]
    for name in sorted(members):
        role = (members[name].get("metadata") or {}).get("hex-arch", {}).get("role", "untagged")
        lines.append('    %s["%s<br/><i>%s</i>"]' % (name.replace("-", "_"), name, role))
    for name in sorted(members):
        for dep in sorted(members[name]["dependencies"], key=lambda d: d["name"]):
            if dep["name"] in members:
                arrow = "-.->" if dep["kind"] == "dev" else "-->"
                lines.append("    %s %s %s" % (name.replace("-", "_"), arrow, dep["name"].replace("-", "_")))
    lines += ["```", ""]
    return "\n".join(lines)


ARM = re.compile(r"\((?:\w+ @ )?\(?([^()]*?)\)?,\s*([^()]*?)\)\s*=>\s*(\w+)::(\w+)", re.S)


def variants(text, enum):
    return re.findall(r"%s::(\w+)" % enum, text)


def machines():
    lines = ["# State machines", "", "Generated by `just views` from each lifecycle's `evolve`. An arm that returns the state it was", "given is not drawn.", ""]
    for path in sorted(glob.glob(os.path.join(ROOT, "domain", "src", "*.rs"))):
        source = open(path).read()
        for match in re.finditer(r"impl Lifecycle for (\w+) \{.*?fn evolve\(self, event: &(\w+)\) -> \w+ \{(.*?)\n    \}\n\}", source, re.S):
            state, event, body = match.group(1), match.group(2), match.group(3)
            initial = re.search(r"fn initial\(\) -> \w+ \{\s*%s::(\w+)" % state, match.group(0)).group(1)
            edges = []
            for arm in ARM.finditer(body):
                if arm.group(3) != state:
                    continue
                for source_state in variants(arm.group(1), state):
                    for trigger in variants(arm.group(2), event):
                        edges.append((source_state, arm.group(4), trigger))
            lines += ["## %s" % state, "", "`%s`" % os.path.relpath(path, ROOT), "", "```mermaid", "stateDiagram-v2", "    [*] --> %s" % initial]
            lines += ["    %s --> %s: %s" % edge for edge in edges]
            lines += ["```", ""]
    return "\n".join(lines)


def main():
    wanted = {"crates.md": crates(), "state-machines.md": machines()}
    if sys.argv[1:] == ["--check"]:
        stale = [name for name, text in wanted.items() if not os.path.exists(os.path.join(OUT, name)) or open(os.path.join(OUT, name)).read() != text]
        for name in stale:
            print("docs/views/%s is stale: run `just views`" % name)
        sys.exit(1 if stale else 0)
    os.makedirs(OUT, exist_ok=True)
    for name, text in wanted.items():
        open(os.path.join(OUT, name), "w").write(text)
        print("wrote docs/views/%s" % name)


main()
