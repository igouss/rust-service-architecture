#!/usr/bin/env python3
import os, re, sys

from workspace import ROOT, Unread, arms, closing, enum_variants, lifecycles, packages, role, split, top

OUT = os.path.join(ROOT, "docs", "views")


def crates():
    members = {p["name"]: p for p in packages()}
    lines = ["# Crate graph", "", "Generated by `just views` from `cargo metadata`. An arrow points from a crate to one it depends on;", "a dotted arrow is a dev-dependency.", "", "```mermaid", "graph TD"]
    for name in sorted(members):
        lines.append('    %s["%s<br/><i>%s</i>"]' % (name.replace("-", "_"), name, role(members[name]) or "untagged"))
    for name in sorted(members):
        for dep in sorted(members[name]["dependencies"], key=lambda d: d["name"]):
            if dep["name"] in members:
                arrow = "-.->" if dep["kind"] == "dev" else "-->"
                lines.append("    %s %s %s" % (name.replace("-", "_"), arrow, dep["name"].replace("-", "_")))
    lines += ["```", ""]
    return "\n".join(lines)


def edges(state, event, body, texts):
    opened = re.search(r"\bfn\s+evolve\s*\(", body)
    block = top(body, "{", opened.end() - 1, len(body)) if opened else len(body)
    inner = top(body, "{", block + 1, len(body))
    if inner == len(body) or not re.fullmatch(r"\s*match\s*\(\s*self\s*,\s*\w+\s*\)\s*", body[block + 1 : inner]) or body[closing(body, inner) + 1 : closing(body, block)].strip():
        raise Unread("%s: `evolve` is not one `match (self, event)`" % state)
    read = arms(body, inner)
    drawn, pairs = [], set()
    for pattern, then in read:
        target = re.match(r"%s::(\w+)\b" % state, then)
        for alternative in split(pattern, "|"):
            if not alternative.strip():
                continue
            text = alternative.strip()
            halves = [half for half in split(text[1:-1], ",") if half.strip()] if text.startswith("(") and closing(text, 0, "()") == len(text) - 1 else []
            given = re.match(r"\s*(\w+)\s*@", halves[0]) if halves else None
            sources, triggers = (re.findall(r"\b%s::(\w+)" % state, halves[0]), re.findall(r"\b%s::(\w+)" % event, halves[1])) if len(halves) == 2 else ([], [])
            if not sources or not triggers:
                raise Unread("%s: the arm `%s` is not a pair of %s and %s variants" % (state, " ".join(text.split()), state, event))
            if not target and not (given and given.group(1) == then):
                raise Unread("%s: `%s` is neither a state nor the state it was given" % (state, " ".join(then.split())))
            pairs |= {(source, trigger) for source in sources for trigger in triggers}
            drawn += [(source, target.group(1), trigger) for source in sources for trigger in triggers] if target else []
    every = {(source, trigger) for source in enum_variants(state, texts) for trigger in enum_variants(event, texts)}
    if pairs != every or len(read) != body[block : closing(body, block)].count("=>"):
        raise Unread("%s: `evolve` has %d pairs of state and event, its arms cover %d" % (state, len(every), len(pairs)))
    return drawn


def machines():
    lines = ["# State machines", "", "Generated by `just views` from each lifecycle's `evolve`. An arm that returns the state it was", "given is not drawn.", ""]
    for _package, path, state, event, body, texts in lifecycles():
        initial = re.search(r"\bfn\s+initial\s*\(\s*\)\s*->\s*\w+\s*\{\s*%s::(\w+)" % state, body)
        if initial is None:
            raise Unread("%s: `initial` does not return a variant of %s" % (state, state))
        lines += ["## %s" % state, "", "`%s`" % os.path.relpath(path, ROOT), "", "```mermaid", "stateDiagram-v2", "    [*] --> %s" % initial.group(1)]
        lines += ["    %s --> %s: %s" % edge for edge in edges(state, event, body, texts)]
        lines += ["```", ""]
    return "\n".join(lines)


def main():
    try:
        wanted = {"crates.md": crates(), "state-machines.md": machines()}
    except Unread as unread:
        print("views: %s; the view would leave it out" % unread)
        print("Fix: write `evolve` as one `match (self, event)` whose arms pair variants and return a state or `s` from `s @`.")
        sys.exit(2)
    if sys.argv[1:] == ["--check"]:
        stale = [name for name, text in wanted.items() if not os.path.exists(os.path.join(OUT, name)) or open(os.path.join(OUT, name)).read() != text]
        for name in stale:
            print("docs/views/%s is stale: run `just views`" % name)
        sys.exit(1 if stale else 0)
    os.makedirs(OUT, exist_ok=True)
    for name, text in wanted.items():
        open(os.path.join(OUT, name), "w").write(text)
        print("wrote docs/views/%s" % name)


main()
